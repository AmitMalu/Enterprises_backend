package com.im.admin.service.impl;

import com.im.admin.entities.ImSubRole;
import com.im.admin.entities.Retailer;
import com.im.admin.entities.RetailerAgent;
import com.im.admin.entities.UserDetails;
import com.im.admin.repositories.ImSubRoleRepository;
import com.im.admin.repositories.RetailerAgentRepository;
import com.im.admin.repositories.RetailerRepository;
import com.im.admin.repositories.UserDetailsRepository;
import com.im.admin.service.RetailerAgentService;
import org.apache.catalina.User;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.stereotype.Service;

@Service
public class RetailerAgentServiceImpl implements RetailerAgentService {

    @Autowired
    private RetailerAgentRepository retailerAgentRepository;

    @Autowired
    private RetailerRepository retailerRepository;

    @Autowired
    private UserDetailsRepository userDetailsRepository;

    @Autowired
    private ImSubRoleRepository imSubRoleRepository;

    @Override
    public RetailerAgent createAgent(RetailerAgent agentRequest) {

        String retailerId = agentRequest.getParentAccount();

        // 1. Check if retailer has already 10 agents
        long existingAgentCount = retailerAgentRepository.countByParentAccount(retailerId);
        if (existingAgentCount >= 10) {
            throw new RuntimeException("Maximum 10 agents allowed per retailer");
        }

        // 2. Fetch retailer by ID
        Retailer retailer = retailerRepository.findByRetailerId(retailerId)
                .orElseThrow(() -> new RuntimeException("Retailer not found with ID: " + retailerId));

        // 3. Copy bank details from retailer
        agentRequest.setBankDetails(retailer.getBankDetails());

        // 4. Save agent (agentId is auto-generated by DB)
        RetailerAgent savedAgent  = retailerAgentRepository.save(agentRequest);

        // 5. Save UserDetails for login
        UserDetails user = new UserDetails();
        user.setMobileNumber(savedAgent.getMobileNumber());
        user.setHierarchyId(retailerId);  // same as parentAccount
        user.setHierarchyCode("RA");   // or "RT" or anything meaningful
        user.setLoginUserName(savedAgent.getUsername());
        user.setLoginPassword(savedAgent.getPassword());
        user.setEmailId(savedAgent.getEmailId());
        user.setCreatedBy(savedAgent.getCreatedBy());
        user.setEditedBy(savedAgent.getCreatedBy());
        user.setUserStatus("Active");     // or "Pending" as per your flow
        user.setUserLoginStatus(false);
        user.setChannel("web");           // optional
        user.setRole_id(savedAgent.getRole_id());

        userDetailsRepository.save(user);  // save into login table

        // 6. Save subRoleIds to ImSubRole table
        if (savedAgent.getSubRoleId() != null) {
            ImSubRole imSubRole = new ImSubRole();
            imSubRole.setMobileNumber(savedAgent.getMobileNumber());
            imSubRole.setSubRoleId(savedAgent.getSubRoleId()); // Save full string like "1.4,1.4,1.3"
            imSubRoleRepository.save(imSubRole);
        }


        return savedAgent;
    }
    }

