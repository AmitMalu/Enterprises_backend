    @Transactional
    @Override
    public RetailerUser createRetailerUser(RetailerUser retailerUser) {

        // Field Validation
        Set<ConstraintViolation<RetailerUser>> violations = validator.validate(retailerUser);
        List<FieldErrorDetailsDTO> errors = violations.stream()
                .map(violation -> new FieldErrorDetailsDTO(violation.getPropertyPath().toString(), violation.getMessage()))
                .collect(Collectors.toList());

        // Phone validation
        try {
            phoneNumberValidationService.validatePhoneNumber(retailerUser.getMobileNumber());
        } catch (IllegalArgumentException ex) {
            errors.add(new FieldErrorDetailsDTO("mobile", ex.getMessage()));
        }

        if (!errors.isEmpty()) {
            throw new CustomValidationException(errors);
        }

        String parentAccount = retailerUser.getParentAccount();

        if (parentAccount == null || !parentAccount.contains("-")) {
            throw new IllegalArgumentException("Invalid parentAccount format. Expected format: 'ABC-XX-001'");
        }

        // Extract prefix from parentAccount
        String abbreviation = parentAccount.split("-")[0];

        // Optionally validate abbreviation format
        if (!abbreviation.matches("^[A-Z]{2,3}$")) {
            throw new IllegalArgumentException("Derived abbreviation '" + abbreviation + "' is invalid. Must be 2 to 3 uppercase letters.");
        }

        retailerUser.setAbbreviation(abbreviation);


        String folder = "RetailerUser";
        retailerUser.setRetailerUserId(idGenerator.generateHierarchyEntityId(folder, "RT"));

        String retailerId = retailerUser.getParentAccount();

        // 1. Check if retailer has already 10 agents
        long existingAgentCount = retailerUserRepository.countByParentAccount(retailerId);
        if (existingAgentCount >= 10) {
            throw new RuntimeException("Maximum 10 RetailerUser allowed per retailer");
        }

        // 2. Fetch retailer by ID
        Retailer retailer = retailerRepository.findByRetailerId(retailerId)
                .orElseThrow(() -> new RuntimeException("Retailer not found with ID: " + retailerId));

        // 3. Copy bank details from retailer
        retailerUser.setBankDetails(retailer.getBankDetails());
        retailerUser.setRetailer(retailer);

        // 4. Save agent (agentId is auto-generated by DB)
        RetailerUser saveRetailerUser = retailerUserRepository.save(retailerUser);

        // 5. Save UserDetails for login
        UserDetails user = new UserDetails();
        user.setMobileNumber(saveRetailerUser.getMobileNumber());
        user.setHierarchyId(saveRetailerUser.getRetailerUserId());
        user.setHierarchyCode("RU");   // or "RT" or anything meaningful
        user.setLoginUserName(saveRetailerUser.getUsername());
        user.setLoginPassword(saveRetailerUser.getPassword());
        user.setEmailId(saveRetailerUser.getEmailId());
        user.setCreatedBy(saveRetailerUser.getCreatedBy());
        user.setEditedBy(saveRetailerUser.getCreatedBy());
        user.setUserStatus("Active");     // or "Pending" as per your flow
        user.setUserLoginStatus(false);
        user.setChannel("web");           // optional
        user.setRole_id(saveRetailerUser.getRole_id());
        user.setParentAccount(parentAccount);

        userDetailsRepository.save(user);  // save into login table

        // 6. Save subRoleIds to ImSubRole table
        if (saveRetailerUser.getSubRoleId() != null) {
            ImSubRole imSubRole = new ImSubRole();
            imSubRole.setMobileNumber(saveRetailerUser.getMobileNumber());
            imSubRole.setSubRoleId(saveRetailerUser.getSubRoleId()); // Save full string like "1.4,1.4,1.3"
            imSubRoleRepository.save(imSubRole);
        }

        return saveRetailerUser;
    }


    @Override
    public CommonResponse<Map<String, Object>> getFilteredUsers(
            String name,
            String mobileNumber,
            String emailId,
            Boolean emailVerified,
            Boolean status,
            int page,
            int size,
            String sortBy,
            String sortDir
    ) {
        Sort sort = sortDir.equalsIgnoreCase("desc")
                ? Sort.by(sortBy).descending()
                : Sort.by(sortBy).ascending();

        Pageable pageable = PageRequest.of(page, size, sort);

        Page<RetailerUserProjection> pagedResult =
                retailerUserRepository.findFiltered(name, mobileNumber, emailId, emailVerified, status, pageable);

        // Wrap data + pagination metadata into map
        Map<String, Object> responseData = new HashMap<>();
        responseData.put("records", pagedResult.getContent());
        responseData.put("totalElements", pagedResult.getTotalElements());
        responseData.put("totalPages", pagedResult.getTotalPages());
        responseData.put("page", page);
        responseData.put("size", size);

        return CommonResponse.<Map<String, Object>>builder()
                .statusCode(HttpStatus.OK.value())
                .message("Users fetched successfully")
                .data(responseData)
                .build();
    }

    @Transactional
    @Override
    public CommonResponse<Void> deleteRetailerUser(String retailerUserId) {
        return retailerUserRepository.findById(retailerUserId)
                .map(user -> {
                    try {
                        // 1. Delete subRoles first
                        if (user.getMobileNumber() != null) {
                            imSubRoleRepository.deleteByMobileNumber(user.getMobileNumber());
                        }

                        // 2. Delete UserDetails next
                        userDetailsRepository.deleteByHierarchyId(user.getRetailerUserId());

                        // 3. Finally delete RetailerUser
                        retailerUserRepository.delete(user);

                        return CommonResponse.<Void>builder()
                                .statusCode(HttpStatus.OK.value())
                                .message("Retailer Agent and related data deleted successfully")
                                .data(null)
                                .build();
                    } catch (Exception e) {
                        return CommonResponse.<Void>builder()
                                .statusCode(HttpStatus.BAD_REQUEST.value())
                                .message("Duplicate entry or constraint violation: " + e.getMessage())
                                .data(null)
                                .build();
                    }
                })
                .orElseGet(() -> CommonResponse.<Void>builder()
                        .statusCode(HttpStatus.NOT_FOUND.value())
                        .message("Retailer Agent not found with id: " + retailerUserId)
                        .data(null)
                        .build()
                );
    }

    @Transactional
    @Override
    public RetailerUser updateRetailerUser(String retailerUserId, RetailerUser retailerUser) {
        RetailerUser existingUser = retailerUserRepository.findById(retailerUserId)
                .orElseThrow(() -> new RuntimeException("Retailer User not found with ID: " + retailerUserId));

        // Update fields (avoid changing parentAccount or bankDetails)
        existingUser.setName(retailerUser.getName());
        existingUser.setMobileNumber(retailerUser.getMobileNumber());
        existingUser.setUsername(retailerUser.getUsername());
        existingUser.setPassword(retailerUser.getPassword());
        existingUser.setEmailId(retailerUser.getEmailId());
        existingUser.setEmailVerified(retailerUser.getEmailVerified());
        existingUser.setStatus(retailerUser.getStatus());
        existingUser.setDob(retailerUser.getDob());
        existingUser.setEditedBy(retailerUser.getEditedBy());

        // Update embedded address
        if (retailerUser.getAdd() != null) {
            if (existingUser.getAdd() == null) {
                existingUser.setAdd(new Address());
            }
            existingUser.getAdd().setOutletName(retailerUser.getAdd().getOutletName());
            existingUser.getAdd().setCompanyType(retailerUser.getAdd().getCompanyType());
            existingUser.getAdd().setCompanyName(retailerUser.getAdd().getCompanyName());
            existingUser.getAdd().setAddress(retailerUser.getAdd().getAddress());
            existingUser.getAdd().setCity(retailerUser.getAdd().getCity());
            existingUser.getAdd().setState(retailerUser.getAdd().getState());
            existingUser.getAdd().setZipCode(retailerUser.getAdd().getZipCode());
        }

        RetailerUser updatedAgent = retailerUserRepository.save(existingUser);

        // Update UserDetails
        userDetailsRepository.findByHierarchyId(retailerUserId).ifPresent(user -> {
            user.setLoginUserName(retailerUser.getUsername());
            user.setLoginPassword(retailerUser.getPassword());
            user.setEmailId(retailerUser.getEmailId());
            user.setEditedBy(retailerUser.getEditedBy());
            userDetailsRepository.save(user);
        });

        // Update subRoles
        if (retailerUser.getSubRoleId() != null) {
            imSubRoleRepository.deleteByMobileNumber(existingUser.getMobileNumber()); // remove old
            ImSubRole imSubRole = new ImSubRole();
            imSubRole.setMobileNumber(existingUser.getMobileNumber());
            imSubRole.setSubRoleId(retailerUser.getSubRoleId());
            imSubRoleRepository.save(imSubRole);
        }

        return updatedAgent;
    }

    @Override
    public CommonResponse<Page<RetailerUserResponseDTO>> getRetailerUsersByRetailerId(
            String retailerId,
            String retailerUserId,
            String abbreviation,
            String name,
            String mobileNumber,
            String username,
            String emailId,
            Boolean emailVerified,
            Boolean status,
            String createdBy,
            String editedBy,
            String role_id,
            String subRoleId,
            LocalDate createdOn,
            int page,
            int size) {

        if (retailerId == null || retailerId.isBlank()) {
            return CommonResponse.handleErrors("Retailer ID cannot be blank");
        }

        Pageable pageable = PageRequest.of(page, size);

        Page<RetailerUser> retailerUsers = retailerUserRepository.findAll((root, query, cb) -> {
            List<Predicate> predicates = new ArrayList<>();

            // mandatory filter
            predicates.add(cb.equal(root.get("parentAccount"), retailerId));

            // optional filters
            if (retailerUserId != null && !retailerUserId.isBlank()) {
                predicates.add(cb.like(cb.lower(root.get("retailerUserId")), "%" + retailerUserId.toLowerCase() + "%"));
            }
            if (abbreviation != null && !abbreviation.isBlank()) {
                predicates.add(cb.like(cb.lower(root.get("abbreviation")), "%" + abbreviation.toLowerCase() + "%"));
            }
            if (name != null && !name.isBlank()) {
                predicates.add(cb.like(cb.lower(root.get("name")), "%" + name.toLowerCase() + "%"));
            }
            if (mobileNumber != null && !mobileNumber.isBlank()) {
                predicates.add(cb.like(cb.lower(root.get("mobileNumber")), "%" + mobileNumber.toLowerCase() + "%"));
            }
            if (username != null && !username.isBlank()) {
                predicates.add(cb.like(cb.lower(root.get("username")), "%" + username.toLowerCase() + "%"));
            }
            if (emailId != null && !emailId.isBlank()) {
                predicates.add(cb.like(cb.lower(root.get("emailId")), "%" + emailId.toLowerCase() + "%"));
            }
            if (emailVerified != null) {
                predicates.add(cb.equal(root.get("emailVerified"), emailVerified));
            }
            if (status != null) {
                predicates.add(cb.equal(root.get("status"), status));
            }
            if (createdBy != null && !createdBy.isBlank()) {
                predicates.add(cb.like(cb.lower(root.get("createdBy")), "%" + createdBy.toLowerCase() + "%"));
            }
            if (editedBy != null && !editedBy.isBlank()) {
                predicates.add(cb.like(cb.lower(root.get("editedBy")), "%" + editedBy.toLowerCase() + "%"));
            }
            if (role_id != null && !role_id.isBlank()) {
                predicates.add(cb.like(cb.lower(root.get("role_id")), "%" + role_id.toLowerCase() + "%"));
            }
            if (subRoleId != null && !subRoleId.isBlank()) {
                predicates.add(cb.like(cb.lower(root.get("subRoleId")), "%" + subRoleId.toLowerCase() + "%"));
            }
            if (createdOn != null) {
                predicates.add(cb.equal(cb.function("DATE", LocalDate.class, root.get("createdOn")), createdOn));
            }

            return cb.and(predicates.toArray(new Predicate[0]));
        }, pageable);

        if (retailerUsers.isEmpty()) {
            return CommonResponse.failure("No Retailer Users found for Retailer ID: " + retailerId);
        }

        // Convert entities to DTOs
        Page<RetailerUserResponseDTO> dtoPage = retailerUsers.map(user -> new RetailerUserResponseDTO(
                user.getRetailerUserId(),
                user.getParentAccount(),
                user.getAbbreviation(),
                user.getName(),
                user.getMobileNumber(),
                user.getUsername(),
                user.getEmailId(),
                user.getEmailVerified(),
                user.getDob(),
                user.getStatus(),
                user.getCreatedOn(),
                user.getCreatedBy(),
                user.getLastEditedOn(),
                user.getEditedBy(),
                user.getCreatedByIPAddress(),
                user.getRole_id(),
                user.getSubRoleId()
        ));

        return CommonResponse.success(dtoPage, "Retailer Users fetched successfully");
    }

